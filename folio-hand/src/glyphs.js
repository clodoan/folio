/**
 * Folio humanist cursive key points — original notebook hand, not Amy Goodchild’s
 * published numeric arrays. Unit box: y 0 = cap, 0.55 = x-height, 1 = baseline,
 * descenders > 1. Each path is [joinTag, {x,y}…, joinTag] with tags 0|1|2|3
 * (0 none, 1 baseline, 2 just above baseline, 3 x-height).
 */

function P(tagIn, xy, tagOut) {
  const pts = [];
  for (let i = 0; i < xy.length; i += 2) pts.push({ x: xy[i], y: xy[i + 1] });
  return [tagIn, ...pts, tagOut];
}

function copyPath(path) {
  return path.map((el) => (typeof el === "number" ? el : { x: el.x, y: el.y }));
}

function G(advance, options, extra = {}) {
  return { advance, options, marks: extra.marks || null, adjust: extra.adjust || defaultAdjust };
}

function defaultAdjust(ip, pc, nc) {
  const start = ip[0];
  const end = ip[ip.length - 1];
  if (pc === 1 && start === 3) {
    ip.splice(1, 0, { x: ip[1].x - 0.12, y: 0.98 });
    ip[0] = 1;
  } else if (pc === 2 && start === 3) {
    ip.splice(1, 0, { x: ip[1].x - 0.08, y: 0.86 });
    ip[0] = 2;
  } else if (pc === 3 && start === 1 && ip.length > 4) {
    ip.splice(1, 1);
  }
  if (nc === 3 && end === 1) {
    const last = ip[ip.length - 2];
    ip[ip.length - 2] = { x: last.x + 0.04, y: 0.72 };
    ip[ip.length - 1] = 2;
  } else if (nc === 1 && end === 3) {
    ip.splice(-1, 0, { x: ip[ip.length - 2].x + 0.06, y: 0.96 });
    ip[ip.length - 1] = 1;
  }
}

function marksOf(letter, n) {
  const g = GLYPHS[letter];
  if (!g || !g.marks) return [];
  const set = g.marks[n] || g.marks[0] || [];
  return set.map(copyPath);
}

export function pickGlyph(letter, n) {
  const g = GLYPHS[letter];
  if (!g) return null;
  const opts = g.options;
  const idx = ((n % opts.length) + opts.length) % opts.length;
  return {
    path: copyPath(opts[idx]),
    marks: marksOf(letter, idx),
    advance: g.advance,
    index: idx,
    adjust: g.adjust,
  };
}

export function glyphCount(letter) {
  return GLYPHS[letter]?.options.length || 0;
}

